
"""
robot_parameters.py
两自由度平面机械臂参数
"""

# 连杆长度 (m)
L1 = 1.0
L2 = 0.8

# 连杆质量 (kg)
m1 = 2.0
m2 = 1.5

# 关节到质心的距离 (m)
lc1 = L1 / 2
lc2 = L2 / 2

# 绕质心Z轴的转动惯量 (kg*m^2)
# 假设连杆为均匀细杆
I1 = m1 * L1**2 / 12
I2 = m2 * L2**2 / 12

# 重力加速度 (m/s^2)
g = 9.81

ROBOT_PARAMS = {
    "L1": L1,
    "L2": L2,
    "m1": m1,
    "m2": m2,
    "lc1": lc1,
    "lc2": lc2,
    "I1": I1,
    "I2": I2,
    "g": g
}
